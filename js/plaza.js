/* =========================================================
   plaza.js — "La Plaza" & Solo Player Progression System

   Responsibilities:
     • Manages a 12-hour cycle of 6 local NPCs (4 Easy, 2 Medium).
     • Persists the daily roster to localStorage.
     • Tracks unlocked NPCs (Free Mode).
     • Tracks win streaks against specific NPCs.
   ========================================================= */

'use strict';

const PlazaSystem = (() => {
    const STORAGE_KEY  = 'astrochess_plaza';
    const CYCLE_MS     = 1 * 60 * 60 * 1000; // 1 hour
    // ↓ Bump this string any time NPC names/avatars change
    //   so old cached rosters are automatically discarded.
    const ROSTER_VERSION = 'v018.1'; // bumped: new NPC roster + scaled ELO

    /**
     * Default state structure.
     */
    function _getDefaultState() {
        return {
            version:   '',
            hourKey:   '', // e.g. "2026-8-20-21"
            roster:    [],
            unlocked:  {}, // { "NPC-name": { ...npcData }, ... }
            streaks:   {}  // { "NPC-name": 2 }
        };
    }

    /**
     * Read from local storage.
     */
    function _getState() {
        try {
            const data = localStorage.getItem(STORAGE_KEY);
            return data ? JSON.parse(data) : _getDefaultState();
        } catch {
            return _getDefaultState();
        }
    }

    /**
     * Write to local storage.
     */
    function _saveState(st) {
        try {
            localStorage.setItem(STORAGE_KEY, JSON.stringify(st));
        } catch {}
    }

    // ── Public API ────────────────────────────────────────

    /**
     * Get the current 6 NPCs in "La Plaza".
     * Rotates every hour, on the hour. Returns mixed difficulty (4 Easy, 2 Medium).
     * NPC ELOs scale with the player's current ELO.
     * If the stored roster was created with an older version, it is discarded.
     */
    function getPlazaRoster() {
        const st  = _getState();
        const date = new Date();
        const currentHourKey = `${date.getFullYear()}-${date.getMonth()}-${date.getDate()}-${date.getHours()}`;

        // Get player ELO for scaling
        const playerProfile = (typeof ProfileSystem !== 'undefined') ? ProfileSystem.getProfile() : null;
        const playerElo = playerProfile ? (playerProfile.elo || 200) : 200;

        // Force refresh if: version changed, hour changed, or roster is incomplete
        const versionMismatch = st.version !== ROSTER_VERSION;
        const hourChanged     = st.hourKey !== currentHourKey;
        const rosterBroken    = !Array.isArray(st.roster) || st.roster.length < 6;

        if (versionMismatch || hourChanged || rosterBroken) {
            // Generate 4 easy, 2 medium UNIQUE NPCs
            st.roster = [];
            const selectedNames = new Set();
            
            const addUniqueNPC = (difficulty) => {
                let npc;
                let attempts = 0;
                do {
                    npc = ProfileSystem.generateNPC(difficulty, playerElo);
                    attempts++;
                } while (selectedNames.has(npc.username) && attempts < 50);
                selectedNames.add(npc.username);
                st.roster.push(npc);
            };

            for(let i = 0; i < 4; i++) addUniqueNPC('easy');
            for(let i = 0; i < 2; i++) addUniqueNPC('medium');

            // Shuffle the roster visually
            st.roster.sort(() => Math.random() - 0.5);
            st.hourKey   = currentHourKey;
            st.version   = ROSTER_VERSION;
            _saveState(st);
        }

        return st.roster;
    }

    /**
     * Get remaining time in milliseconds for the current Plaza cycle.
     */
    function getRemainingTime() {
        const now = new Date();
        const nextHour = new Date(now);
        nextHour.setHours(now.getHours() + 1, 0, 0, 0);
        return Math.max(0, nextHour.getTime() - now.getTime());
    }

    /**
     * Get array of unlocked NPCs (for Free Mode).
     */
    function getUnlockedOpponents() {
        return Object.values(_getState().unlocked);
    }

    /**
     * Unlock an NPC permanently.
     * @param {object} npc Profile generated by ProfileSystem
     * @returns {boolean} true if it was newly unlocked, false if already unlocked.
     */
    function unlockOpponent(npc) {
        if (!npc || !npc.id) return false;
        const st = _getState();
        if (!st.unlocked[npc.id]) {
            st.unlocked[npc.id] = npc;
            _saveState(st);
            return true;
        }
        return false;
    }

    /**
     * Check if an NPC is unlocked.
     */
    function isUnlocked(npcId) {
        return !!_getState().unlocked[npcId];
    }

    /**
     * Record a match result against an NPC to update streaks.
     */
    function recordMatchResult(npcId, won) {
        const st = _getState();
        if (!st.streaks[npcId]) st.streaks[npcId] = 0;
        
        if (won) {
            st.streaks[npcId]++;
        } else {
            st.streaks[npcId] = 0; // reset streak on loss
        }
        _saveState(st);
    }

    /**
     * Get current win streak against a specific NPC.
     */
    function getStreak(npcId) {
        return _getState().streaks[npcId] || 0;
    }

    return {
        getPlazaRoster,
        getRemainingTime,
        getUnlockedOpponents,
        unlockOpponent,
        isUnlocked,
        recordMatchResult,
        getStreak
    };

})();

